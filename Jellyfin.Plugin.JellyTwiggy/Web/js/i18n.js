    function detectLanguage() {
        const candidates = [document.documentElement.getAttribute('lang'), navigator.language];
        for (const candidate of candidates) {
            const code = (candidate || '').slice(0, 2).toLowerCase();
            if (dictionaries[code]) {
                return code;
            }
        }
        return 'en';
    }

    function format(template, params) {
        return template.replace(/\{(\w+)\}/g, (match, name) => (params && name in params ? params[name] : match));
    }

    // t('key', params) — plural entries pick the form by params.count (or params.watched).
    JT.t = function (key, params) {
        const language = detectLanguage();
        const value = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
        if (typeof value === 'string') {
            return format(value, params);
        }

        const count = params?.count ?? params?.watched ?? params?.total ?? 0;
        const form = new Intl.PluralRules(language).select(count);
        return format(value[form] ?? value.other, params);
    };

    JT.language = detectLanguage;

    // Lets feature modules ship their own strings: JT.addStrings({ en: {...}, ru: {...}, de: {...} }).
    JT.addStrings = function (strings) {
        for (const [language, values] of Object.entries(strings)) {
            Object.assign(dictionaries[language] || (dictionaries[language] = {}), values);
        }
    };
